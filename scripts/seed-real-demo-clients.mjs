function buildInsert(row) {
  const columns = [
    'ativo',
    'client_name',
    'clinic_name',
    'telefone',
    'vendedor',
    'criativo',
    'equipe',
    'faturamento',
    'faturamento_personalizado',
    'pacote',
    'periodo',
    'indicacao',
    'entrada',
    'is_mrr',
    'mrr_entrada',
    'mrr_remaining',
    'data_entrada',
    'stage',
    'last_stage_change',
    'lost_reason',
    'no_show_reason',
    'notes',
    'agendado_por',
    'agendado_via',
    'pagador_anuncio',
    'tem_socio',
    'tem_mkt',
    'tem_secretaria',
    'salao_ou_clinica',
    'pode_investir',
    'meeting_date',
    'meeting_time',
    'followup_done',
  ];

  const values = [
    row.ativo ?? base.ativo,
    row.client_name,
    row.clinic_name,
    row.telefone,
    row.vendedor,
    row.criativo,
    row.equipe ?? base.equipe,
    row.faturamento,
    null,
    row.pacote ?? base.pacote,
    row.periodo ?? 'MENSAL',
    row.indicacao ?? base.indicacao,
    row.entrada ?? 0,
    row.is_mrr ?? false,
    row.mrr_entrada ?? row.entrada ?? 0,
    row.mrr_remaining ?? 0,
    row.data_entrada,
    row.stage ?? 'NOVO',
    row.last_stage_change ?? null,
    row.lost_reason ?? null,
    row.no_show_reason ?? null,
    row.notes ?? null,
    row.agendado_por,
    row.agendado_via,
    row.pagador_anuncio ?? base.pagador_anuncio,
    row.tem_socio,
    row.tem_mkt,
    row.tem_secretaria,
    row.salao_ou_clinica,
    row.pode_investir,
    row.meeting_date,
    row.meeting_time,
    row.followup_done ?? base.followup_done,
  ];

  return { columns, values };
}

async function main() {
  const client = new Client({
    connectionString,
    ssl: { rejectUnauthorized: false },
  });

  await client.connect();
  await client.query('begin');

  try {
    let inserted = 0;

    for (const row of rows) {
      const { columns, values } = buildInsert(row);
      const params = values.map((_, index) => `$${index + 1}`).join(', ');
      const sql = `
        insert into public.pipeline_clients (${columns.join(', ')})
        select ${params}
        where not exists (
          select 1
          from public.pipeline_clients
          where telefone = $4 or client_name = $2
        )
      `;

      const result = await client.query(sql, values);
      inserted += result.rowCount || 0;
    }

    await client.query('commit');
    console.log(JSON.stringify({ inserted }));
  } catch (error) {
    await client.query('rollback');
    throw error;
  } finally {
    await client.end();
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
